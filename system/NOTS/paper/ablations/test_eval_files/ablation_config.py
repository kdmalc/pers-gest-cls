def apply_smoke(config: dict, smoke: bool) -> dict:
    config["smoke"] = bool(smoke)
    if smoke:
        config["num_epochs"] = 1
        config["episodes_per_epoch_train"] = 48
        config["val_episodes_per_user"] = 5        # 20 val episodes
        config["test_episodes_per_user"] = 10      # 40 test episodes
        print("[smoke] SMOKE RUN: 1 epoch x 48 training episodes, 20 val / 40 test episodes -- "
              "results are NOT meaningful and are rejected by the aggregator")
    return config


def save_results(results: dict, config: dict, tag: str = "",
                 n_test_pids: int = None, n_folds: int = None):
    """Save results dict as JSON to RUN_DIR.

    Every JSON now carries a `protocol_check` block written by
    `assert_protocol_consistent()`. This exists because the declared
    `test_procedure` and the executed protocol have already diverged in shipped
    results (the few-shot grid JSONs say "L2SO" while evaluating 4 fixed test
    subjects). Auditing from `test_procedure` alone gives the wrong answer;
    `protocol_check.effective_protocol` gives the right one.

    n_test_pids / n_folds are optional overrides for callers that know the true
    shape of the run — e.g. an L2SO driver that has already fanned out folds.
    When omitted they are inferred from config["test_PIDs"].
    """
    import json
    ablation_id = config["ablation_id"]
    ts          = config["timestamp"]
    fname       = f"{ablation_id}_{ts}{('_' + tag) if tag else ''}_results.json"
    fpath       = RUN_DIR / fname

    # Stamp the real protocol alongside the declared one. Non-fatal by design:
    # a mismatch is sometimes intentional, but it must never be silent.
    if not isinstance(results, dict):
        results = {"results": results}
    results = dict(results)
    # Provenance: the launcher exports GIT_REV (git is not available on compute nodes). None means
    # "not launched through the launcher" and is recorded as such, never invented.
    results["git_rev"] = os.environ["GIT_REV"] if "GIT_REV" in os.environ else None
    results["smoke"] = bool(config["smoke"]) if "smoke" in config else False
    results["emg_repr"] = config["emg_repr"]          # always set by make_base_config / apply_emg_repr
    results["hpo_config"] = config["hpo_config"] if "hpo_config" in config else None
    results["hpo_source"] = config["hpo_source"] if "hpo_source" in config else None
    results["protocol_check"] = assert_protocol_consistent(
        config, n_test_pids=n_test_pids, n_folds=n_folds
    )

    with open(fpath, "w") as f:
        json.dump(results, f, indent=2)
    print(f"[save_results] Saved to {fpath}")


def save_model_checkpoint(state: dict, config: dict, tag: str = "best"):
    ablation_id = config["ablation_id"]
    ts          = config["timestamp"]
    fname       = f"{ablation_id}_{ts}_{tag}.pt"
    fpath       = RUN_DIR / fname
    torch.save(state, fpath)
    print(f"[save_checkpoint] Saved to {fpath}")
    return str(fpath)


def count_parameters(model) -> int:
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


