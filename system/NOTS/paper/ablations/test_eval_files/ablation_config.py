    config["models_save_dir"]          = str(RUN_DIR)
    config["emg_imu_pkl_full_path"]    = str(DATA_DIR / "filtered_datasets"
                                              / "metadata_IMU_EMG_allgestures_allusers.pkl")
    config["dfs_load_path"]  = str(CODE_DIR / "dataset" / "meta-learning-sup-que-ds") + "/"
    config["pretrain_dir"]   = str(CODE_DIR / "pretrain_outputs" / "checkpoints") + "/"
    config["NOTS"] = True   # cluster run flag (keeps old local-path logic from triggering)

    # ── User splits ───────────────────────────────────────────────────────────
    # Default PIDs = kfold7 fold 0; scripts overwrite per fold via apply_kfold_fold().
    # all_PIDs = the 28 evaluated users.
    _f0 = kfold_split.get_fold(0)
    config["train_PIDs"] = _f0["train"]
    config["val_PIDs"]   = _f0["val"]
    config["test_PIDs"]  = _f0["test"]
    config["all_PIDs"]   = list(KFOLD_ALL_TEST_PIDS)
    config["fold_idx"]   = 0
    config["val_episode_source"] = "val"   # "val" | "dev" | "sampled" (see get_maml_dataloaders)
    # Cached val episodes used per user for checkpoint selection (file has 50/user; dev file 100/user).
    # 25/user = 100 episodes per epoch: a 10-way episode costs ~3x a 3-way one. None = all.
    config["val_episodes_per_user"] = 25
    config["test_episodes_per_user"] = None   # None = all 200 cached test episodes per user and cell
    config["hpo_val_PIDs"] = list(KFOLD_HPO_VAL_PIDS)

